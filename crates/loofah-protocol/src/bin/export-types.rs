use loofah_protocol::*;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut types = specta::TypeCollection::default();
    types
        .register::<Capabilities>()
        .register::<ProcessingPolicy>()
        .register::<ProcessingSettingsSnapshot>()
        .register::<SaveProcessingSettingsRequest>()
        .register::<ProcessingSettingsSaveOutcome>()
        .register::<SummaryJobRequest>()
        .register::<ProcessingJobSnapshot>()
        .register::<ListProcessingJobsInput>()
        .register::<ProcessingJobPage>()
        .register::<ProcessingJobResult>()
        .register::<ListMeetingsInput>()
        .register::<GetMeetingInput>()
        .register::<GetMeetingTranscriptInput>()
        .register::<SearchMeetingsInput>()
        .register::<AgentMeeting>()
        .register::<AgentExport>()
        .register::<AgentPage>()
        .register::<AgentTranscript>()
        .register::<AgentSearchPage>()
        .register::<RenderedTranscriptSegment>()
        .register::<FileInfo>()
        .register::<FileMetadata>()
        .register::<RecordingLease>()
        .register::<AttachmentLease>()
        .register::<AttachmentPage>()
        .register::<RecordingWaveform>()
        .register::<DeleteRecordingRequest>()
        .register::<RemoveAttachmentRequest>()
        .register::<UploadAttachmentRequest>()
        .register::<AttachmentUploadStatus>()
        .register::<AudioPeaks>()
        .register::<VaultInfo>()
        .register::<VaultMutation>()
        .register::<Membership>()
        .register::<Me>()
        .register::<CreateVaultRequest>()
        .register::<UpdateVaultRequest>()
        .register::<SetMembershipRequest>()
        .register::<CreateSessionRequest>()
        .register::<SessionDocument>()
        .register::<SessionPage>()
        .register::<EnhancedDoc>()
        .register::<DocumentTarget>()
        .register::<DocumentSnapshot>()
        .register::<SaveDocumentRequest>()
        .register::<DocumentSaveOutcome>()
        .register::<PersonItem>()
        .register::<TagItem>()
        .register::<TaskItem>()
        .register::<TaskInput>()
        .register::<TaskSource>()
        .register::<TasksSnapshot>()
        .register::<ReplaceTasksRequest>()
        .register::<TasksSaveOutcome>()
        .register::<TranscriptWithData>()
        .register::<RemoteAuthConfig>()
        .register::<ApplicationError>()
        .register::<SaveNoteRequest>()
        .register::<NoteEditorSnapshot>()
        .register::<SaveNoteEditorRequest>()
        .register::<NoteEditorSaveOutcome>()
        .register::<MetadataSnapshot>()
        .register::<SaveMetadataRequest>()
        .register::<MetadataSaveOutcome>()
        .register::<NoteSaveOutcome>()
        .register::<ChangeEvent>()
        .register::<StartupStatus>();
    let content = specta_typescript::Typescript::default()
        .header("// Generated by cargo run -p loofah-protocol --bin export-types. Do not edit.")
        .bigint(specta_typescript::BigIntExportBehavior::Number)
        .export(&types)?;
    let content = content
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        .trim_end()
        .to_owned()
        + "\n";
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/desktop/src/shared/application/protocol.gen.ts");
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(&path)? != content {
            return Err("generated application protocol is out of date".into());
        }
    } else {
        std::fs::create_dir_all(path.parent().unwrap())?;
        std::fs::write(path, content)?;
    }
    Ok(())
}
